// Composition round-trip (S2 P2) — the two-package version of S1's
// produce→verify round-trip (produce-core `src/produce-verify-roundtrip.test.ts`):
//
//   DERIVE (civic-typed-harness)  →  ASSEMBLE (@typedstandards/produce-core)
//        →  SIGN (test key, generated in-test)  →  VERIFY OFFLINE
//                        (@typedstandards/verify-core §9.2)
//
// The derive leg runs the harness's full capture machinery end-to-end on a
// SYNTHETIC multi-source analysis — the area S1's fixtures don't reach (their
// envelope cases all carry empty traces, single-source dataSources, and
// mcpServers: [] environments): TraceBuilder capture (injected clock + seeded
// RNG, demo-default identity config), skill-span extraction, multi-source
// dataSources population, the 20+-node PROV-O graph, and the datHere policy
// derivation whose environment extension carries the skill span's MCP server.
// No captured fixture is involved: the trace is DERIVED live and
// deterministically in-test (provenance: generated by this suite's
// `captureAnalysis()` below, from the literal inputs it writes into the
// spans).
//
// P1's verified finding, honored here: verify-core's computeContentHashSha256
// THROWS on the dathere-ag-jupyter/v1 rule unless
// extensions['org.civicaitools.notebook'] is present — the real publish flow
// supplies the executed notebook, so this composition supplies a stub
// notebook extension on the datHere chain (same as P1's derive→assemble
// seam test in src/format/dathere.test.ts).
//
// Offline is ENFORCED, not assumed: the injected fetcher throws, so any
// network dependence in the asserted checks would fail the test.
//
// Fixture convention (owner-directed): the injected clock keeps every
// nanosecond timestamp under 13 digits (millisecond values stay ≤ 6 digits,
// so `<ms>000000` is ≤ 12 digits), and the seeded RNG emits bytes in
// 0xa0–0xef only — every id byte's hex starts with a letter nibble, so no
// long decimal-digit run can occur. The serialized package is asserted
// digit-run-free below.

